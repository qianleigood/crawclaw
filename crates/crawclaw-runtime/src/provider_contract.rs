fn json_string(value: &str) -> String {
    serde_json::to_string(value).expect("string literal encodes as JSON")
}

fn is_javascript_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first == '$' || first == '_' || first.is_ascii_alphabetic()) {
        return false;
    }
    chars.all(|ch| ch == '$' || ch == '_' || ch.is_ascii_alphanumeric())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bundled_provider_auth_env_var_module_uses_rust_provider_metadata() {
        let source = render_bundled_provider_auth_env_var_module();
        assert!(source.contains("anthropic: [\"ANTHROPIC_OAUTH_TOKEN\", \"ANTHROPIC_API_KEY\"],"));
        assert!(source.contains(
            "\"github-copilot\": [\"COPILOT_GITHUB_TOKEN\", \"GH_TOKEN\", \"GITHUB_TOKEN\"],"
        ));
        assert!(source.contains("openai: [\"OPENAI_API_KEY\"],"));
        assert!(!source.contains("openai-codex"));
    }

    #[test]
    fn provider_runtime_constants_module_uses_rust_provider_metadata() {
        let source = render_provider_runtime_constants_module();
        assert!(source.contains("export const CLAUDE_CLI_BACKEND_ID = \"claude-cli\";"));
        assert!(source.contains("export const ANTHROPIC_VERTEX_DEFAULT_REGION = \"global\";"));
        assert!(
            source.contains("export const OLLAMA_DEFAULT_BASE_URL = \"http://127.0.0.1:11434\";")
        );
        assert!(source.contains("export const OLLAMA_DEFAULT_CONTEXT_WINDOW = 128000;"));
    }
}
