fn bundled_capability_metadata_payload() -> (
    Vec<BundledCapabilityMetadataEntry>,
    BTreeMap<String, String>,
    BTreeMap<String, String>,
) {
    let mut entries = BTreeMap::<String, BundledCapabilityMetadataEntryBuilder>::new();
    let mut legacy_aliases = BTreeMap::<String, String>::new();
    let mut auto_enable_provider_plugins = BTreeMap::<String, String>::new();

    for metadata in crawclaw_providers::bundled_provider_plugin_contract_metadata() {
        let entry = entries.entry(metadata.plugin_id.clone()).or_default();
        entry.provider_ids.extend(metadata.provider_ids);
        for legacy_plugin_id in metadata.legacy_plugin_ids {
            legacy_aliases.insert(legacy_plugin_id, metadata.plugin_id.clone());
        }
        for provider_id in metadata.auto_enable_when_configured_providers {
            auto_enable_provider_plugins.insert(provider_id, metadata.plugin_id.clone());
        }
    }

    for descriptor in crawclaw_native_plugins::registry::builtin_native_plugin_descriptors() {
        let entry = entries.entry(descriptor.plugin_id.clone()).or_default();
        entry.provider_ids.extend(
            descriptor
                .model_providers
                .into_iter()
                .map(|provider| provider.id),
        );
        entry.speech_provider_ids.extend(
            descriptor
                .speech_providers
                .into_iter()
                .map(|provider| provider.id),
        );
        entry.web_fetch_provider_ids.extend(
            descriptor
                .web_fetch_providers
                .into_iter()
                .map(|provider| provider.id),
        );
        entry.web_search_provider_ids.extend(
            descriptor
                .web_search_providers
                .into_iter()
                .map(|provider| provider.id),
        );
        entry
            .tool_names
            .extend(descriptor.tools.into_iter().map(|tool| tool.name));
    }

    let snapshots = entries
        .into_iter()
        .map(|(plugin_id, entry)| entry.into_entry(plugin_id))
        .filter(|entry| !entry.is_empty())
        .collect();

    (snapshots, legacy_aliases, auto_enable_provider_plugins)
}

fn render_bundled_capability_snapshots(entries: &[BundledCapabilityMetadataEntry]) -> String {
    if entries.is_empty() {
        return "[]".to_string();
    }
    let rendered_entries = entries
        .iter()
        .map(|entry| {
            format!(
                "  {{\n    pluginId: {plugin_id},\n    providerIds: {provider_ids},\n    speechProviderIds: {speech_provider_ids},\n    webFetchProviderIds: {web_fetch_provider_ids},\n    webSearchProviderIds: {web_search_provider_ids},\n    toolNames: {tool_names},\n  }},",
                plugin_id = json_string(&entry.plugin_id),
                provider_ids = render_string_array(&entry.provider_ids),
                speech_provider_ids = render_string_array(&entry.speech_provider_ids),
                web_fetch_provider_ids = render_string_array(&entry.web_fetch_provider_ids),
                web_search_provider_ids = render_string_array(&entry.web_search_provider_ids),
                tool_names = render_string_array(&entry.tool_names),
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!("[\n{rendered_entries}\n]")
}

fn render_provider_auth_choices(
    choices: &[crawclaw_providers::BundledProviderAuthChoice],
) -> String {
    if choices.is_empty() {
        return "[]".to_string();
    }
    let rendered_choices = choices
        .iter()
        .map(render_provider_auth_choice)
        .collect::<Vec<_>>()
        .join("\n");
    format!("[\n{rendered_choices}\n]")
}

fn render_provider_auth_choice(choice: &crawclaw_providers::BundledProviderAuthChoice) -> String {
    let mut fields = vec![
        format!("    pluginId: {},", json_string(&choice.plugin_id)),
        format!("    providerId: {},", json_string(&choice.provider)),
        format!("    methodId: {},", json_string(&choice.method)),
        format!("    choiceId: {},", json_string(&choice.choice_id)),
        format!("    choiceLabel: {},", json_string(&choice.choice_label)),
    ];
    if let Some(choice_hint) = choice.choice_hint.as_deref() {
        fields.push(format!("    choiceHint: {},", json_string(choice_hint)));
    }
    if !choice.deprecated_choice_ids.is_empty() {
        fields.push(format!(
            "    deprecatedChoiceIds: {},",
            render_string_array(&choice.deprecated_choice_ids),
        ));
    }
    fields.push(format!("    groupId: {},", json_string(&choice.group_id)));
    fields.push(format!(
        "    groupLabel: {},",
        json_string(&choice.group_label)
    ));
    if let Some(group_hint) = choice.group_hint.as_deref() {
        fields.push(format!("    groupHint: {},", json_string(group_hint)));
    }
    if let Some(option_key) = choice.option_key.as_deref() {
        fields.push(format!("    optionKey: {},", json_string(option_key)));
    }
    if let Some(cli_flag) = choice.cli_flag.as_deref() {
        fields.push(format!("    cliFlag: {},", json_string(cli_flag)));
    }
    if let Some(cli_option) = choice.cli_option.as_deref() {
        fields.push(format!("    cliOption: {},", json_string(cli_option)));
    }
    if let Some(cli_description) = choice.cli_description.as_deref() {
        fields.push(format!(
            "    cliDescription: {},",
            json_string(cli_description)
        ));
    }
    format!("  {{\n{}\n  }},", fields.join("\n"))
}

fn render_string_record(entries: &BTreeMap<String, String>) -> String {
    if entries.is_empty() {
        return "{}".to_string();
    }
    let rendered_entries = entries
        .iter()
        .map(|(key, value)| {
            format!(
                "  {key}: {value},",
                key = render_javascript_property_key(key),
                value = json_string(value),
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!("{{\n{rendered_entries}\n}}")
}

fn render_string_array(values: &[String]) -> String {
    if values.is_empty() {
        return "[]".to_string();
    }
    let rendered_values = values
        .iter()
        .map(|value| json_string(value))
        .collect::<Vec<_>>()
        .join(", ");
    format!("[{rendered_values}]")
}

fn render_javascript_property_key(value: &str) -> String {
    if is_javascript_identifier(value) {
        value.to_string()
    } else {
        json_string(value)
    }
}

fn json_string(value: &str) -> String {
    serde_json::to_string(value).expect("string literal encodes as JSON")
}

fn is_javascript_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first == '$' || first == '_' || first.is_ascii_alphabetic()) {
        return false;
    }
    chars.all(|ch| ch == '$' || ch == '_' || ch.is_ascii_alphanumeric())
}

