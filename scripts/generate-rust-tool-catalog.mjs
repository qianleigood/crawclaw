#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const repoRoot = resolve(new URL("..", import.meta.url).pathname);
const toolchain = process.env.CRAWCLAW_RUST_TOOLCHAIN ?? "+stable";
const result = spawnSync(
  "cargo",
  [toolchain, "run", "-q", "-p", "crawclaw-runtime", "--", "status", "--json"],
  {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 16,
  },
);

if (result.status !== 0) {
  process.stderr.write(result.stderr);
  process.stderr.write(result.stdout);
  process.exit(result.status ?? 1);
}

const status = JSON.parse(result.stdout);
const catalog = status.toolCatalog;
if (!catalog?.sections || !catalog?.coreTools || !catalog?.nativeTools) {
  throw new Error("crawclaw-runtime status did not include toolCatalog");
}

const header = [
  "// Generated by scripts/generate-rust-tool-catalog.mjs.",
  "// Source of truth: crates/crawclaw-runtime/src/lib.rs.",
  "// Do not edit by hand.",
  "",
].join("\n");

const body = [
  `export const RUST_CORE_TOOL_SECTIONS = ${JSON.stringify(catalog.sections, null, 2)} as const;`,
  "",
  `export const RUST_CORE_TOOL_DEFINITIONS = ${JSON.stringify(catalog.coreTools, null, 2)} as const;`,
  "",
  `export const RUST_NATIVE_TOOL_DEFINITIONS = ${JSON.stringify(catalog.nativeTools, null, 2)} as const;`,
  "",
].join("\n");

writeFileSync(resolve(repoRoot, "src/agents/rust-tool-catalog.generated.ts"), header + body);
